import type { IsoDate } from '../models/common.ts';
import type { OccurrenceRecord, Routine, RoutineOccurrence } from '../models/routine.ts';
import { eachDay } from './date.ts';
import { routineOccursOn } from './recurrence.ts';

/**
 * The schedule in a date range: every hit of every routine's rule, overlaid
 * with what was recorded. Pure, so the server builds the day view with it and
 * the phone rebuilds the same day offline from its cached rules.
 *
 * A recorded occurrence that the current rule no longer generates — because the
 * routine was paused or its rule edited — is still surfaced, so past adherence
 * never rewrites itself.
 */
export interface OccurrenceSources {
	routines: Routine[];
	/** What the day view shows of each session, by id. */
	sessions: ReadonlyMap<string, { name: string; estimatedDurationSec: number }>;
	/** Recorded deviations, keyed `routineId|date`. */
	records: ReadonlyMap<string, OccurrenceRecord>;
}

export function occurrenceKey(routineId: string, date: IsoDate): string {
	return `${routineId}|${date}`;
}

export function buildOccurrences(
	{ routines, sessions, records }: OccurrenceSources,
	from: IsoDate,
	to: IsoDate
): RoutineOccurrence[] {
	if (routines.length === 0) return [];

	const byId = new Map(routines.map((routine) => [routine.id, routine]));
	const emitted = new Set<string>();
	const result: RoutineOccurrence[] = [];

	const emit = (routine: Routine, date: IsoDate, record: OccurrenceRecord | undefined) => {
		const key = occurrenceKey(routine.id, date);
		if (emitted.has(key)) return;
		emitted.add(key);
		const session = sessions.get(routine.sessionId);
		result.push({
			routineId: routine.id,
			routineName: routine.name || session?.name || 'Routine',
			sessionId: routine.sessionId,
			sessionName: session?.name ?? 'Deleted session',
			date,
			timeOfDay: routine.timeOfDay,
			estimatedDurationSec: session?.estimatedDurationSec ?? 0,
			status: record?.status ?? 'pending',
			workoutId: record?.workoutId ?? null,
			resolvedAt: record?.resolvedAt ?? null
		});
	};

	for (const date of eachDay(from, to)) {
		for (const routine of routines) {
			if (routineOccursOn(routine, date)) {
				emit(routine, date, records.get(occurrenceKey(routine.id, date)));
			}
		}
	}

	// Anything already recorded but no longer generated by the rule.
	for (const record of records.values()) {
		if (record.date < from || record.date > to) continue;
		const routine = byId.get(record.routineId);
		if (routine) emit(routine, record.date, record);
	}

	return result.sort(
		(a, b) =>
			a.date.localeCompare(b.date) ||
			(a.timeOfDay ?? '99:99').localeCompare(b.timeOfDay ?? '99:99') ||
			a.routineName.localeCompare(b.routineName)
	);
}
