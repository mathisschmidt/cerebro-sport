import type { IsoDate } from '$domain/models/common.ts';
import type {
	OccurrenceResolution,
	RoutineDetail,
	RoutineInput,
	RoutineOccurrence,
	RoutinePatch
} from '$domain/models/routine.ts';
import type { SessionSummary } from '$domain/models/session.ts';
import { routineOccursOn } from '$domain/services/recurrence.ts';
import { eachDay, todayIso } from '$domain/services/date.ts';
import { routineRepository } from '../repositories/routine.repository.ts';
import { sessionRepository } from '../repositories/session.repository.ts';
import { notFound, validationFailed } from '../http/errors.ts';
import type { Routine } from '$domain/models/routine.ts';
import type { OccurrenceRecord } from '../repositories/routine.repository.ts';

/**
 * Routines and the schedule they generate.
 *
 * The calendar is always derived from the rules, then overlaid with recorded
 * completions. A recorded occurrence that the current rule no longer generates
 * — because the routine was paused or its rule edited — is still surfaced, so
 * past adherence never rewrites itself.
 */

function displayName(routine: Routine, session: SessionSummary | undefined): string {
	return routine.name || session?.name || 'Routine';
}

function toDetail(routine: Routine, sessions: Map<string, SessionSummary>): RoutineDetail {
	const session = sessions.get(routine.sessionId);
	return {
		...routine,
		name: routine.name,
		sessionName: session?.name ?? 'Deleted session',
		estimatedDurationSec: session?.estimatedDurationSec ?? 0
	};
}

function loadSessions(routines: Routine[]): Map<string, SessionSummary> {
	return sessionRepository.findSummariesByIds([...new Set(routines.map((r) => r.sessionId))]);
}

export const routineService = {
	list(): RoutineDetail[] {
		const routines = routineRepository.list();
		const sessions = loadSessions(routines);
		return routines.map((routine) => toDetail(routine, sessions));
	},

	get(id: string): RoutineDetail {
		const routine = routineRepository.findById(id);
		if (!routine) throw notFound('Routine not found');
		return toDetail(routine, loadSessions([routine]));
	},

	create(input: RoutineInput): RoutineDetail {
		assertSessionExists(input.sessionId);
		assertWindow(input.startDate, input.endDate);
		const routine = routineRepository.create(input);
		return toDetail(routine, loadSessions([routine]));
	},

	update(id: string, patch: RoutinePatch): RoutineDetail {
		if (patch.sessionId) assertSessionExists(patch.sessionId);
		const existing = routineRepository.findById(id);
		if (!existing) throw notFound('Routine not found');
		assertWindow(patch.startDate ?? existing.startDate, patch.endDate !== undefined ? patch.endDate : existing.endDate);

		const routine = routineRepository.update(id, patch);
		if (!routine) throw notFound('Routine not found');
		return toDetail(routine, loadSessions([routine]));
	},

	remove(id: string): void {
		if (!routineRepository.remove(id)) throw notFound('Routine not found');
	},

	/**
	 * Every occurrence in `[from, to]`, ordered by date then time of day.
	 */
	occurrences(from: IsoDate, to: IsoDate): RoutineOccurrence[] {
		const routines = routineRepository.list();
		if (routines.length === 0) return [];

		const sessions = loadSessions(routines);
		const records = routineRepository.findOccurrences(from, to);
		const byId = new Map(routines.map((routine) => [routine.id, routine]));
		const emitted = new Set<string>();
		const result: RoutineOccurrence[] = [];

		const emit = (routine: Routine, date: IsoDate, record: OccurrenceRecord | undefined) => {
			const key = `${routine.id}|${date}`;
			if (emitted.has(key)) return;
			emitted.add(key);
			const session = sessions.get(routine.sessionId);
			result.push({
				routineId: routine.id,
				routineName: displayName(routine, session),
				sessionId: routine.sessionId,
				sessionName: session?.name ?? 'Deleted session',
				date,
				timeOfDay: routine.timeOfDay,
				estimatedDurationSec: session?.estimatedDurationSec ?? 0,
				status: record?.status ?? 'pending',
				workoutId: record?.workoutId ?? null,
				resolvedAt: record?.resolvedAt ?? null
			});
		};

		for (const date of eachDay(from, to)) {
			for (const routine of routines) {
				if (routineOccursOn(routine, date)) {
					emit(routine, date, records.get(`${routine.id}|${date}`));
				}
			}
		}

		// Anything already recorded but no longer generated by the rule.
		for (const record of records.values()) {
			const routine = byId.get(record.routineId);
			if (routine) emit(routine, record.date, record);
		}

		return result.sort(
			(a, b) =>
				a.date.localeCompare(b.date) ||
				(a.timeOfDay ?? '99:99').localeCompare(b.timeOfDay ?? '99:99') ||
				a.routineName.localeCompare(b.routineName)
		);
	},

	/** The agenda for one day. */
	day(date: IsoDate = todayIso()): RoutineOccurrence[] {
		return this.occurrences(date, date);
	},

	resolve(resolution: OccurrenceResolution): RoutineOccurrence {
		const routine = routineRepository.findById(resolution.routineId);
		if (!routine) throw notFound('Routine not found');
		routineRepository.resolveOccurrence(resolution);
		const day = this.day(resolution.date).find((o) => o.routineId === resolution.routineId);
		if (!day) throw notFound('Occurrence not found');
		return day;
	}
};

function assertSessionExists(sessionId: string): void {
	if (!sessionRepository.findSummary(sessionId)) {
		throw validationFailed('That session no longer exists', { sessionId: 'Unknown session' });
	}
}

function assertWindow(startDate: IsoDate, endDate: IsoDate | null): void {
	if (endDate && endDate < startDate) {
		throw validationFailed('The end date must come after the start date', {
			endDate: 'Must be after the start date'
		});
	}
}
